INTRO = "<p>Ten cases that get harder as you go: <strong>painful bone metastases</strong>, <strong>cord compression</strong>, <strong>benign disease</strong> (Dupuytren, heterotopic ossification), <strong>impending fracture</strong>, <strong>SVC syndrome</strong>, <strong>trigeminal neuralgia</strong>, an <strong>AVM</strong>, <strong>prophylactic and oligometastatic</strong> radiation, and a <strong>goals-of-care</strong> consult at the end of life. Each starts with a one-liner, then gives you more information step by step: the <strong>imaging</strong>, the <strong>scores</strong> that decide the plan, the <strong>fractionation</strong>, the <strong>landmark trials</strong>, and what to tell the patient. Some steps are multiple choice, some are fill-in-the-blank.</p>"

def shuffle_choices(cases):
    """The app shows choices in stored order, so vary where the answer sits.
    Deterministic per prompt; ordered lists (grades, ECOG) keep their order."""
    import random
    for c in cases:
        for st in c["steps"]:
            if st.pop("ordinal", False) or "choices" not in st:
                continue
            right = st["choices"][st["correctIndex"]]
            random.Random(st["prompt"]).shuffle(st["choices"])
            st["correctIndex"] = st["choices"].index(right)


if __name__ == "__main__":
    shuffle_choices(CASES)
    write("palliative", INTRO, CASES)
